function bboxToPolygon(bbox) {
  if (!bbox) return null
  const [w, s, e, n] = bbox
  return {
    type: 'Polygon',
    coordinates: [[[w, s], [e, s], [e, n], [w, n], [w, s]]],
  }
}

function targetHref(collection, itemId) {
  return `/stac/collections/${collection}/items/${itemId}`
}

function relationLink(rel, collection, itemId, title) {
  return {
    rel,
    href: targetHref(collection, itemId),
    type: 'application/geo+json',
    title,
  }
}

function makeItem({
  id,
  collection,
  title,
  displayName,
  originalFilename,
  dataCategory,
  status,
  datetime,
  bbox = null,
  geometry = undefined,
  fallbackCenter = null,
  size,
  assetKey = 'data',
  assetTitle,
  links = [],
  missingRequiredFields = [],
  metadataGaps = [],
  draftReason = null,
  extraProperties = {},
}) {
  const preview = getMockPreviewAsset(id)
  const finalGeometry = geometry === undefined ? bboxToPolygon(bbox) : geometry
  const assets = {
    [assetKey]: {
      href: `mock://assets/${id}/${originalFilename}`,
      title: assetTitle || title,
      roles: ['data'],
    },
  }

  if (preview.thumbnailHref) {
    assets.thumbnail = {
      href: preview.thumbnailHref,
      title: `${title} thumbnail`,
      roles: ['thumbnail'],
    }
  }

  return {
    type: 'Feature',
    stac_version: '1.0.0',
    id,
    collection,
    bbox: bbox || undefined,
    geometry: finalGeometry || null,
    properties: {
      title,
      display_name: displayName || title,
      description: displayName || title,
      datetime,
      'project:name': collectionTitle[collection],
      'project:site': collectionSite[collection],
      'project:campaign': collectionCampaign[collection],
      data_category: dataCategory,
      status,
      'sams:status': status,
      previewStatus: preview.status,
      previewType: preview.previewType,
      previewFailureReason: preview.failureReason || null,
      originalFilename,
      'file:name': originalFilename,
      'file:size': size,
      missingRequiredFields,
      metadataGaps,
      draftReason,
      'mock:fallback_center': fallbackCenter,
      'mock:spatial_state': bbox ? (finalGeometry ? 'geometry' : 'bbox') : (fallbackCenter ? 'fallback' : 'none'),
      ...extraProperties,
    },
    assets,
    links: [
      { rel: 'self', href: targetHref(collection, id), type: 'application/geo+json' },
      { rel: 'collection', href: `/stac/collections/${collection}`, type: 'application/json', title: collectionTitle[collection] },
      ...links,
    ],
  }
}

